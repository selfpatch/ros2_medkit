#pragma once

#include <cstddef>
#include <optional>
#include <string>
#include <unordered_map>
#include <unordered_set>
#include <vector>

#include "ros2_medkit_gateway/core/discovery/models/app.hpp"
#include "ros2_medkit_gateway/core/discovery/models/area.hpp"
#include "ros2_medkit_gateway/core/discovery/models/component.hpp"
#include "ros2_medkit_gateway/core/discovery/models/function.hpp"

namespace ros2_medkit_gateway {

/**
 * @brief Merges entities from a remote peer gateway with local entities.
 *
 * Type-aware merge logic:
 * - Area: merge by ID (combine tags/description, no duplication)
 * - Function: merge by ID (combine hosts lists)
 * - Component: merge by ID (combine tags/description, no duplication)
 * - App: prefix remote ID with "peername__" on collision
 *
 * A remote Component or App whose ID an entity of another type holds is
 * prefixed the same way, and so is a remote Area or Function that has no local
 * entity of its own type to merge with: routing and several lookups are keyed
 * by ID alone, and the remote entity under that ID would take the other
 * entity's place in them. The entity of another type is a local one, or one
 * this merger already added for the same peer: a peer that declares Area x
 * and Component x is served as Area x and Component <peer>__x.
 *
 * A prefixed ID is reserved against every ID already merged (whatever its type),
 * every ID the peer itself declares, and every ID this merger generated for
 * another entity of any type. When it is taken, the remote entity is dropped,
 * the drop is recorded per type, and the peer's references to it are removed
 * rather than left to name the local entity that shares its ID. An ID a merge
 * generated is never a merge target: a remote entity declared under one is
 * another entity.
 *
 * Given the IDs the peer declares, a reference one of its entities makes -
 * a host, a parent, an Area, a Component an App is located on, a dependency -
 * resolves only to an entity that peer declared: renamed, dropped, or kept
 * under its own ID. Any other is removed. The peer's ID for something it never
 * declared names, here, whatever holds that ID: a peer Function hosting
 * `admin` next to a local App `admin` would group the local App.
 *
 * After merging, a routing table maps remote entity IDs (possibly prefixed)
 * to the peer name, enabling request forwarding. Merged Areas and Functions do
 * NOT appear in the routing table; a merged Component does (see merge_components).
 */
class EntityMerger {
 public:
  /// IDs the merge target holds before this peer is merged into it, one set per
  /// entity type: the local gateway's own entities and every peer merged before.
  /// Also used for the IDs a peer declares.
  struct LocalIds {
    std::unordered_set<std::string> areas;
    std::unordered_set<std::string> components;
    std::unordered_set<std::string> apps;
    std::unordered_set<std::string> functions;
    /// The IDs among those that an earlier merge generated by prefixing
    /// (entities whose `original_id` is set), whatever their type.
    std::unordered_set<std::string> generated;
  };

  /// Original remote ID -> the prefixed ID it is served under, per entity type.
  struct Renames {
    std::unordered_map<std::string, std::string> areas;
    std::unordered_map<std::string, std::string> components;
    std::unordered_map<std::string, std::string> apps;
    std::unordered_map<std::string, std::string> functions;
  };

  /// A merger that compares each remote entity only with local entities of its
  /// own type, which is all a caller that merges one collection needs.
  explicit EntityMerger(const std::string & peer_name);

  /// A merger that also keeps every remote entity out of an ID a local entity
  /// of another type holds, and every prefixed ID out of the IDs `peer_ids`
  /// says the peer declares. With `peer_ids`, a reference the peer makes
  /// resolves only to an entity among them. The merge pass over a whole peer
  /// uses this one.
  EntityMerger(const std::string & peer_name, LocalIds local_ids, std::optional<LocalIds> peer_ids = std::nullopt);

  /// The IDs of the given entities, ready to pass to the constructor.
  static LocalIds collect_ids(const std::vector<Area> & areas, const std::vector<Component> & components,
                              const std::vector<App> & apps, const std::vector<Function> & functions);

  /**
   * @brief Merge local and remote Areas by ID.
   *
   * Same area ID from both local and remote yields one Area entity.
   * Remote-only areas are added with source tagged as "peer:<name>".
   * A remote subarea whose parent was prefixed names the prefixed parent.
   */
  std::vector<Area> merge_areas(const std::vector<Area> & local, const std::vector<Area> & remote);

  /**
   * @brief Merge local and remote Functions by ID, combining hosts lists.
   *
   * Same function ID from both local and remote yields one Function with
   * the union of hosts from both sides. A remote host that names an App or
   * Component this merger prefixed names the prefixed ID, so call this after
   * merge_apps and merge_components.
   */
  std::vector<Function> merge_functions(const std::vector<Function> & local, const std::vector<Function> & remote);

  /**
   * @brief Merge local and remote Components by ID.
   *
   * Same component ID from both local and remote yields one Component entity
   * with merged tags and description, and the remote's area when the local one
   * names none. The merged Component routes to the peer. A local entity of another type
   * holding the ID would be routed with it, so in that case the remote
   * Component is prefixed instead of merged. Remote-only components are added
   * with source tagged as "peer:<name>". References to an Area merge_areas
   * prefixed, or to a Component this call prefixed, name the prefixed ID.
   */
  std::vector<Component> merge_components(const std::vector<Component> & local, const std::vector<Component> & remote);

  /**
   * @brief Merge local and remote Apps with prefix on collision.
   *
   * If a remote App has the same ID as a local one, the remote entity
   * gets its ID prefixed with "peername__". A remote App located on a
   * Component merge_components prefixed names the prefixed Component.
   */
  std::vector<App> merge_apps(const std::vector<App> & local, const std::vector<App> & remote);

  /**
   * @brief Get the routing table: entity_id -> peer_name for remote entities.
   *
   * Prefixed entities map their prefixed ID. Merged entities (Area/Function)
   * do not appear in the routing table. Non-colliding remote Components/Apps
   * still appear because they need request forwarding.
   */
  const std::unordered_map<std::string, std::string> & get_routing_table() const;

  /// The remote IDs this merger prefixed, original -> prefixed.
  const Renames & get_renames() const;

  /// Remote entities left out because their prefixed ID is taken, or is not a
  /// valid entity ID, as "<Type> '<id>' (<why>)". Serving one would put two
  /// entities under one ID, or one under an ID no request can name.
  const std::vector<std::string> & get_dropped() const;

  /// The remote IDs left out, one set per type, by the peer's own IDs. A
  /// reference the peer makes to one of them is removed from its entities.
  const LocalIds & get_drops() const;

  /// Separator used for prefixing remote entity IDs on collision.
  static constexpr const char * SEPARATOR = "__";

  /// The longest name, in bytes, a prefixed entity is served under:
  /// `<peer>__<name>` is cut to it at a UTF-8 character boundary. The peer's
  /// name is bounded only by the text a refresh may read (16 MB), and the
  /// served name is copied into every forwarded object that names the entity.
  static constexpr size_t kMaxServedNameBytes = 512;

 private:
  enum class Kind { kArea, kComponent, kApp, kFunction };

  std::string peer_name_;
  LocalIds local_ids_;
  LocalIds peer_ids_;
  /// The peer's IDs are known, so a reference to an ID it did not declare is
  /// removed.
  bool checks_references_{false};
  std::unordered_map<std::string, std::string> routing_table_;
  Renames renames_;
  std::vector<std::string> dropped_;
  LocalIds drops_;
  /// The IDs of the remote entities this merger added, as served, per type.
  LocalIds added_;

  /// The remote entity an ID was generated for: its type and its own ID.
  struct GeneratedFor {
    Kind kind;
    std::string original_id;
  };
  /// Every ID this merger generated, -> the remote entity it was generated for.
  std::unordered_map<std::string, GeneratedFor> generated_;

  /// Create a prefixed ID: "peername__original_id"
  std::string prefix_id(const std::string & id) const;

  /// The name a prefixed entity is served under: "peername__name", cut to
  /// kMaxServedNameBytes.
  std::string prefix_name(const std::string & name) const;

  /// Create the source tag for remote entities: "peer:<name>"
  std::string peer_source() const;

  /// True when a local entity, or a remote one this merger added, of a type
  /// other than `kind` holds `id`.
  bool held_by_other_type(const std::string & id, Kind kind) const;

  /// True when a local entity of any type holds `id`.
  bool held_by_any_type(const std::string & id) const;

  /// True when `id` is free to be generated for the remote `original_id` of
  /// `kind`: no local entity of any type holds it, the peer declares no entity
  /// by it, and this merger generated it for no other entity. An entity of
  /// another type with the same original ID is another entity: two served
  /// under one ID would share its route. Only the same entity listed twice
  /// gets it again.
  bool can_generate(const std::string & id, Kind kind, const std::string & original_id) const;

  /// Record `id`, generated for the remote `original_id` of `kind`.
  void record_generated(const std::string & id, Kind kind, const std::string & original_id);

  /// Record `original_id` of `kind` as dropped, for the reason `why`.
  void drop(Kind kind, const std::string & original_id, const std::string & why);

  /// Drop `original_id` of `kind` when `generated_id`, its prefixed ID, is not
  /// a valid entity ID (validate_entity_id): longer than 256 characters, which
  /// a peer ID of 250 under a peer name of 8 already is, or holding a
  /// character a peer name brought in. Requests answer 400 for such an ID, so
  /// the entity could be listed but never addressed. True when dropped.
  bool drop_if_unaddressable(Kind kind, const std::string & original_id, const std::string & generated_id);

  /// A Function's hosts, which name the peer's own Apps or Components, as the
  /// IDs they are served under, each once; a dropped one, and one the peer
  /// declared neither as App nor as Component, is removed.
  void resolve_hosts(std::vector<std::string> & hosts) const;

  /// The IDs of one type the peer declares, or nullptr when they are not
  /// known and no reference is checked against them.
  const std::unordered_set<std::string> * declared(const std::unordered_set<std::string> & ids) const;
};

}  // namespace ros2_medkit_gateway
